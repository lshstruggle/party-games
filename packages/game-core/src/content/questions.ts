export function questionsOf(type: 'truth' | 'dare', spice: 'mild' | 'spicy'): Question[] {
  return QUESTIONS.filter((q) => q.type === type && q.spice === spice)
}

/** 微辣关闭时只取温和；开启时按 6:4 混合，避免整晚都是八卦 */
export function availableQuestions(type: 'truth' | 'dare', spice: 'mild' | 'spicy'): Question[] {
  return spice === 'spicy'
    ? QUESTIONS.filter((q) => q.type === type)
    : QUESTIONS.filter((q) => q.type === type && q.spice === 'mild')
}
